<?php
/**
 * One-time installer: writes config/config.php, creates the tables, seeds the draws,
 * gallery and default settings, and creates the first GMF admin account.
 * Locks itself afterwards (storage/installed.lock). Delete this file once done.
 */
require __DIR__ . '/includes/bootstrap.php';

$lock = APP_ROOT . '/storage/installed.lock';
if (is_file($lock)) {
    http_response_code(403);
    exit('Already installed. Delete storage/installed.lock to run the installer again (this does not remove data).');
}

$existing = is_file(APP_ROOT . '/config/config.php');
$errors = [];
$done = false;
$v = fn ($k, $d = '') => (string) ($_POST[$k] ?? $d);

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $db = $existing
        ? config('db')
        : ['host' => $v('db_host', 'localhost'), 'port' => (int) $v('db_port', '3306'), 'name' => $v('db_name'), 'user' => $v('db_user'), 'pass' => $v('db_pass')];
    $adminEmail = mb_strtolower(trim($v('admin_email')));
    if (!filter_var($adminEmail, FILTER_VALIDATE_EMAIL) || strlen($v('admin_password')) < 10 || trim($v('admin_name')) === '') {
        $errors[] = 'Enter an admin name, a valid email and a password of at least 10 characters.';
    }
    if (!$errors) {
        try {
            $pdo = new PDO("mysql:host={$db['host']};port={$db['port']};charset=utf8mb4", $db['user'], $db['pass'], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
            try {
                $pdo->exec('CREATE DATABASE IF NOT EXISTS `' . str_replace('`', '', $db['name']) . '` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci');
            } catch (Throwable $e) {
                // cPanel users usually cannot create databases from PHP — the DB must already exist.
            }
            $pdo->exec('USE `' . str_replace('`', '', $db['name']) . '`');
        } catch (Throwable $e) {
            $errors[] = 'Database connection failed: ' . $e->getMessage();
        }
    }

    if (!$errors) {
        // 1. Config file
        if (!$existing) {
            $cfg = require APP_ROOT . '/config/config.sample.php';
            $cfg['base_url'] = rtrim(trim($v('base_url')), '/');
            $cfg['env'] = $v('env') === 'development' ? 'development' : 'production';
            $cfg['app_secret'] = bin2hex(random_bytes(32));
            $cfg['partner_api_key'] = bin2hex(random_bytes(24));
            $cfg['db'] = $db;
            $cfg['mail']['driver'] = in_array($v('mail_driver'), ['smtp', 'mail', 'log'], true) ? $v('mail_driver') : 'log';
            foreach (['host', 'username', 'password', 'from_email'] as $k) {
                if ($v('mail_' . $k) !== '') {
                    $cfg['mail'][$k] = $v('mail_' . $k);
                }
            }
            $cfg['mail']['port'] = (int) $v('mail_port', '465');
            $cfg['mail']['encryption'] = $cfg['mail']['port'] === 587 ? 'tls' : 'ssl';
            $php = "<?php\n// Generated by install.php on " . date('Y-m-d H:i') . ". Edit freely.\nreturn " . var_export($cfg, true) . ";\n";
            if (!@file_put_contents(APP_ROOT . '/config/config.php', $php)) {
                $errors[] = 'Could not write config/config.php — check folder permissions.';
            }
        }
    }

    if (!$errors) {
        // 2. Schema
        foreach (array_filter(array_map('trim', explode(';', (string) file_get_contents(APP_ROOT . '/database/schema.sql')))) as $sql) {
            if (!preg_match('/^(--[^\n]*\n\s*)*$/', $sql)) {
                $pdo->exec($sql);
            }
        }
        $now = date('Y-m-d H:i:s');

        // 3. Settings defaults (keeps any existing values)
        $st = $pdo->prepare('INSERT IGNORE INTO settings (skey, svalue) VALUES (?, ?)');
        foreach (setting_defaults() as $k => $val) {
            $st->execute([$k, $val]);
        }

        // 4. Draws
        $st = $pdo->prepare('INSERT IGNORE INTO draws (draw_key, title, prize_description, scheduled_for, created_at) VALUES (?, ?, ?, ?, ?)');
        $st->execute(['event_day', 'Second Prize — Runner-up', '', '2026-10-31', $now]);
        $st->execute(['final', 'Grand Prize — Top Referrer', "Return flights for two\nWeekend accommodation\nShuttle transfers included", '2026-10-31', $now]);

        // 5. Gallery seed from the partnership proposal imagery
        if (!(int) $pdo->query('SELECT COUNT(*) FROM media')->fetchColumn()) {
            $st = $pdo->prepare('INSERT INTO media (kind, title, caption, src, album, featured, sort_order, created_at) VALUES (\'image\', ?, ?, ?, ?, ?, ?, ?)');
            $seed = [
                ['crowd-night', 'Under the lights', 'The GMF crowd after dark', 'Festival', 1],
                ['performer-stage', 'On stage', 'Live at a George Musical Festival show', 'Festival', 1],
                ['activation-02', 'Taxi rank activation', 'Meeting commuters across the Garden Route', 'Street activations', 1],
                ['activation-22', 'Street team, George', 'Flyering with the FLY FOR TWO crew', 'Street activations', 1],
                ['activation-04', 'Forecourt stop', 'Eden Soul & Jazz on the road', 'Street activations', 1],
                ['airport-terminal', 'George Airport', 'Where the weekend away begins', 'Travel', 1],
                ['activation-23', 'Pop-up partners', 'Activation with local partners', 'Street activations', 1],
                ['activation-21', 'Poster run', 'Eden Soul & Jazz posters around town', 'Street activations', 0],
                ['activation-24', 'Crew', 'The GMF promoters', 'Street activations', 0],
            ];
            for ($i = 1; $i <= 20; $i++) {
                $name = sprintf('activation-%02d', $i);
                if (!in_array($name, array_column($seed, 0), true)) {
                    $seed[] = [$name, 'On the ground', 'GMF ground activation', 'Street activations', 0];
                }
            }
            foreach ($seed as $i => [$file, $title, $cap, $album, $feat]) {
                if (is_file(APP_ROOT . "/assets/img/gallery/{$file}.jpg")) {
                    $st->execute([$title, $cap, "assets/img/gallery/{$file}.jpg", $album, $feat, $i * 10, $now]);
                }
            }
        }

        // 6. First admin
        $pdo->prepare('INSERT INTO admins (name, email, password_hash, role, created_at) VALUES (?, ?, ?, \'admin\', ?)
                       ON DUPLICATE KEY UPDATE password_hash = VALUES(password_hash), role = \'admin\'')
            ->execute([trim($v('admin_name')), $adminEmail, password_hash($v('admin_password'), PASSWORD_DEFAULT), $now]);

        foreach (['storage/logs', 'storage/draws', 'uploads/media'] as $dir) {
            if (!is_dir(APP_ROOT . '/' . $dir)) {
                @mkdir(APP_ROOT . '/' . $dir, 0775, true);
            }
        }
        @file_put_contents($lock, date('c'));
        $done = true;
    }
}
